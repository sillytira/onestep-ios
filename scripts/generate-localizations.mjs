import fs from 'node:fs';import path from 'node:path';import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const {locales,entries}=JSON.parse(fs.readFileSync(path.join(root,'config/ui-translations.json'),'utf8'));
const result={};for(const [index,language] of locales.entries()){
 result[language]={};for(const [key,values] of Object.entries(entries)){if(values.length!==locales.length||!values[index])throw Error('Missing translation: '+key);result[language][key]=values[index];}
}
fs.writeFileSync(path.join(root,'portable/lib/translations.dart'),'// Generated by scripts/generate-localizations.mjs; edit config/ui-translations.json.\nconst Map<String,Map<String,String>> translations = '+JSON.stringify(result,null,2)+';\n');
for(const language of ['en',...locales]){
 const directory=path.join(root,'OneStep',language+'.lproj');fs.mkdirSync(directory,{recursive:true});
 fs.writeFileSync(path.join(directory,'Localizable.strings'),Object.keys(entries).map(k=>JSON.stringify(k)+' = '+JSON.stringify(language==='en'?k:result[language][k])+';').join('\n')+'\n');
}
console.log('Generated '+Object.keys(entries).length+' core UI translations in '+locales.join(', '));
